"""
Проверка закономерностей в простых числах.

Для каждой тысячи и каждой сотни внутри неё вычисляем:
  сумма разниц = последнее простое в сотне - первое простое в сотне

Проверяем гипотезу: сотни 1, 3, 7 одинаковые; сотни 6, 8 одинаковые;
паттерн инвертируется при смене чётности тысяч.
"""

MAX = 20000  # до какого числа проверяем


def решето(n):
    простые = [True] * (n + 1)
    простые[0] = простые[1] = False
    for i in range(2, int(n**0.5) + 1):
        if простые[i]:
            for j in range(i * i, n + 1, i):
                простые[j] = False
    return [i for i in range(2, n + 1) if простые[i]]


def сумма_разниц(простые_в_сотне):
    if len(простые_в_сотне) < 2:
        return None
    return простые_в_сотне[-1] - простые_в_сотне[0]


def анализ_тысячи(все_простые, старт):
    результат = {}
    for сотня in range(10):
        от = старт + сотня * 100
        до = от + 99
        в_сотне = [p for p in все_простые if от <= p <= до]
        результат[сотня] = сумма_разниц(в_сотне)
    return результат


все_простые = решето(MAX)

